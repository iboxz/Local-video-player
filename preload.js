const { contextBridge, ipcRenderer } = require("electron");

contextBridge.exposeInMainWorld("electronAPI", {
  selectVideoFiles: (defaultPath) => ipcRenderer.invoke("select-video-files", defaultPath),
  selectDefaultFolder: () => ipcRenderer.invoke("select-default-folder"),
  selectSubtitleFiles: () => ipcRenderer.invoke("select-subtitle-files"),
  findSidecarSubs: (src) => ipcRenderer.invoke("find-sidecar-subs", src),
  selectSubtitleFile: () => ipcRenderer.invoke("select-subtitle-file"),
  searchSubtitles: (params) => ipcRenderer.invoke("subtitle-search", params),
  downloadSubtitle: (params) => ipcRenderer.invoke("subtitle-download", params),
  openExternal: (url) => ipcRenderer.invoke("open-external", url),
  getInstalledFonts: () => ipcRenderer.invoke("get-installed-fonts"),
  loadStore: () => ipcRenderer.invoke("store-load"),
  saveStore: (data) => ipcRenderer.invoke("store-save", data),
  prepareVideo: (fileUrl, force) => ipcRenderer.invoke("prepare-video", fileUrl, force),
  onPrepareProgress: (cb) => ipcRenderer.on("prepare-progress", (_, data) => cb && cb(data)),
  onPrepareDone: (cb) => ipcRenderer.on("prepare-done", (_, data) => cb && cb(data)),
  onPrepareError: (cb) => ipcRenderer.on("prepare-error", (_, data) => cb && cb(data)),
  onMouseNav: (cb) => ipcRenderer.on("mouse-nav", (_, dir) => cb && cb(dir)),
  probeTracks: (fileUrl) => ipcRenderer.invoke("probe-tracks", fileUrl),
  probeChapters: (fileUrl) => ipcRenderer.invoke("probe-chapters", fileUrl),
  probeInfo: (fileUrl) => ipcRenderer.invoke("probe-info", fileUrl),
  selectVideoFolder: () => ipcRenderer.invoke("select-video-folder"),
  onOpenTargets: (cb) => ipcRenderer.on("open-targets", (_, items) => cb && cb(items)),
  winIntegrationStatus: () => ipcRenderer.invoke("win-integration-status"),
  winIntegrationSet: (kind, on) => ipcRenderer.invoke("win-integration-set", kind, on),
  winOpenDefaultApps: () => ipcRenderer.invoke("win-open-default-apps"),
  getThumb: (src) => ipcRenderer.invoke("get-thumb", src),
  probeBitrate: (src, start, span) => ipcRenderer.invoke("probe-bitrate", src, start, span),
  audioLiveInfo: () => ipcRenderer.invoke("audio-live-info"),
  audioLivePlan: (src) => ipcRenderer.invoke("audio-live-plan", src),
  fileExists: (u) => ipcRenderer.invoke("file-exists", u),
  filesMissing: (l) => ipcRenderer.invoke("files-missing", l),
  onMediaCommand: (cb) => ipcRenderer.on("media-command", (_, c) => cb && cb(c)),
  setThumbarIcons: (icons) => ipcRenderer.send("thumbar-icons", icons),
  setThumbarState: (st) => ipcRenderer.send("thumbar-state", st),
  setTaskbarProgress: (frac, mode) => ipcRenderer.send("taskbar-progress", frac, mode),
  switchAudioTrack: (params) => ipcRenderer.invoke("switch-audio-track", params),
  saveScreenshot: (dataUrl) => ipcRenderer.invoke("save-screenshot", dataUrl),
  getCacheInfo: () => ipcRenderer.invoke("get-cache-info"),
  clearCache: () => ipcRenderer.invoke("clear-cache"),
  getHardwareDecode: () => ipcRenderer.invoke("get-hardware-decode"),
  setHardwareDecode: (enabled) => ipcRenderer.invoke("set-hardware-decode", enabled),
  relaunchApp: () => ipcRenderer.invoke("relaunch-app"),
  windowControl: {
    minimize: () => ipcRenderer.send("window-control", "minimize"),
    maximize: () => ipcRenderer.send("window-control", "maximize"),
    close: () => ipcRenderer.send("window-control", "close"),
  },
});
