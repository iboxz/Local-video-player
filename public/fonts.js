// تابع برای پر کردن لیست فونت‌ها در صفحه
function populateFontSelect(selectElement) {
  fonts.forEach((font) => {
    const option = document.createElement("option");
    option.value = font;
    option.textContent = font;
    selectElement.appendChild(option);
  });
}
